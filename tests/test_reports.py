from __future__ import annotations

import json
from pathlib import Path

from jcheng_benchmark.model import load_suite
from jcheng_benchmark.report import render_markdown, write_json, write_markdown
from jcheng_benchmark.runner import run_suite

ROOT = Path(__file__).resolve().parents[1]
FIXTURE_SUITE = ROOT / "tests" / "fixtures" / "synthetic" / "suite.yaml"
FIXTURE_DATA = ROOT / "tests" / "fixtures" / "synthetic" / "samples.jsonl"


def _report() -> dict:
    return run_suite(
        load_suite(FIXTURE_SUITE),
        FIXTURE_DATA,
        operator_name="unit-test",
        host="ci",
        generated_at="2026-11-26T00:00:00Z",
        notes=("generated by tests",),
    )


def test_markdown_contains_provenance_and_limitations() -> None:
    text = render_markdown(_report())
    assert "# Benchmark report —" in text
    assert "synthetic" in text
    assert "not a hardware" in text
    assert "sha256" in text
    assert "generated by tests" in text
    assert "not an acceptance report" in text


def test_json_round_trips(tmp_path: Path) -> None:
    report = _report()
    path = tmp_path / "nested" / "report.json"
    write_json(path, report)
    reloaded = json.loads(path.read_text(encoding="utf-8"))
    assert reloaded == report
    assert reloaded["generated_at"] == "2026-11-26T00:00:00Z"


def test_markdown_writer_creates_parents(tmp_path: Path) -> None:
    path = tmp_path / "nested" / "report.md"
    write_markdown(path, _report())
    assert path.is_file()
    assert path.read_text(encoding="utf-8").startswith("# Benchmark report")
